package cn.reverie.gui.clickgui.irc
import cn.reverie.nocturne.NocturneAuth
import cn.reverie.render.core.RenderEngine
import cn.reverie.render.draw.CornerRadii
import cn.reverie.render.draw.RoundedRect
import cn.reverie.render.nanovg.NanoVGColor
import cn.reverie.render.nanovg.NanoVGImage
import cn.reverie.render.nanovg.NanoVGPaint
import cn.reverie.render.nanovg.NanoVGRenderer
import org.lwjgl.BufferUtils
import org.lwjgl.nanovg.NVGPaint
import org.lwjgl.system.MemoryStack
import java.net.URI
import java.util.concurrent.ConcurrentHashMap
import kotlin.concurrent.thread

/** IRC images only accept PNG URLs generated by the official upload API. Downloads are asynchronous and NanoVG textures are created on the render thread. */
internal object IrcImageCache {
    private const val MAX_IMAGE_BYTES = 2 * 1024 * 1024
    private val allowedPath = Regex("/api/irc/images/[A-Za-z0-9_-]{24}\\.png")
    private val imageLinkPattern = Regex("https://[^\\s]+/api/irc/images/[A-Za-z0-9_-]{24}\\.png")
    private val states = ConcurrentHashMap<String, State>()
    private sealed interface State {
        data object Loading : State
        data class Ready(val bytes: ByteArray) : State
        data object Failed : State
    }

    private val images = object : LinkedHashMap<String, NanoVGImage>(48, 0.75f, true) {
        override fun removeEldestEntry(eldest: MutableMap.MutableEntry<String, NanoVGImage>?): Boolean {
            if (size <= 48) return false
            eldest?.value?.close()
            eldest?.key?.let { states.remove(it) }
            return true
        }
    }

    fun imageUrl(text: String): String? {
        val candidate = imageLinkPattern.find(text)?.value?.trimEnd('.', ',', ')', ']', '>', '"', '\'') ?: return null
        return candidate.takeIf(::isAllowedUrl)
    }

    fun previewHeight(): Float = 104f

    fun draw(url: String, x: Float, y: Float, maxW: Float, maxH: Float, alpha: Float) {
        NanoVGRenderer.drawRoundedRect(x, y, maxW, maxH, 6f, NanoVGColor(0f, 0f, 0f, 0.20f * alpha))
        val image = imageFor(url)
        if (image == null) {
            val failed = states[url] == State.Failed
            NanoVGRenderer.drawCenteredString(
                if (failed) "Failed to load image" else "Loading image…",
                x + maxW * 0.5f, y + maxH * 0.5f,
                NanoVGColor(0.68f, 0.70f, 0.75f, 0.82f * alpha), 8.5f
            )
            NanoVGRenderer.drawRoundedOutline(x, y, maxW, maxH, 6f, NanoVGColor(1f, 1f, 1f, 0.08f * alpha), 0.8f)
            return
        }
        val scale = minOf(maxW / image.width.coerceAtLeast(1), maxH / image.height.coerceAtLeast(1))
        val drawW = image.width * scale
        val drawH = image.height * scale
        val drawX = x + (maxW - drawW) * 0.5f
        val drawY = y + (maxH - drawH) * 0.5f
        MemoryStack.stackPush().use { stack ->
            val paint = NVGPaint.malloc(stack)
            NanoVGPaint.imagePattern(
                RenderEngine.nanoVG.handle, drawX, drawY, drawW, drawH, 0f,
                image.imageHandle, alpha.coerceIn(0f, 1f), paint
            )
            RoundedRect.draw(RenderEngine.nanoVG.handle, drawX, drawY, drawW, drawH, CornerRadii(5f), paint)
        }
        NanoVGRenderer.drawRoundedOutline(x, y, maxW, maxH, 6f, NanoVGColor(1f, 1f, 1f, 0.10f * alpha), 0.8f)
    }

    private fun imageFor(url: String): NanoVGImage? {
        synchronized(images) { images[url]?.let { return it } }
        when (val state = states[url]) {
            null -> {
                if (states.putIfAbsent(url, State.Loading) == null) {
                    thread(name = "Nocturne-IRC-Image", isDaemon = true) {
                        states[url] = fetch(url)?.let(State::Ready) ?: State.Failed
                    }
                }
            }
            is State.Ready -> {
                val buffer = BufferUtils.createByteBuffer(state.bytes.size)
                buffer.put(state.bytes).flip()
                val decoded = try {
                    NanoVGImage.createFromMemory(RenderEngine.nanoVG.handle, buffer)
                } catch (_: Throwable) {
                    null
                }
                if (decoded != null && decoded.isValid) {
                    synchronized(images) { images[url] = decoded }
                    return decoded
                }
                states[url] = State.Failed
            }
            State.Loading, State.Failed -> Unit
        }
        return null
    }

    private fun isAllowedUrl(raw: String): Boolean = try {
        val uri = URI(raw)
        val base = URI(NocturneAuth.API_BASE)
        uri.scheme.equals("https", true) && uri.host.equals(base.host, true) &&
            (uri.port == -1 || uri.port == base.port) && allowedPath.matches(uri.path ?: "")
    } catch (_: Throwable) {
        false
    }

    private fun fetch(raw: String): ByteArray? {
        if (!isAllowedUrl(raw)) return null
        return try {
            val path = URI(raw).rawPath ?: return null
            val (statusCode, bytes) = NocturneAuth.signedRequestBytes(path)
            if (statusCode != 200 || bytes.size > MAX_IMAGE_BYTES) return null
            if (bytes.size < 24 || !bytes.copyOfRange(0, 8).contentEquals(
                    byteArrayOf(0x89.toByte(), 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A)
                )) null else bytes
        } catch (_: Throwable) {
            null
        }
    }
}
